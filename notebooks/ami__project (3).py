def summarize_segment(segment_text, keywords, max_sentences=3):
    """
    Simple extractive summary:
    - Rank sentences by the number of keyword matches.
    - Pick top N sentences for the summary.
    """
    sentences = sent_tokenize(segment_text)
    ranked = []
    for s in sentences:
        score = sum(s.lower().count(k) for k in keywords)
        ranked.append((score, s))
    # Sort descending by score
    ranked.sort(reverse=True)
    # Take top N sentences
    summary_sentences = [s for score, s in ranked[:max_sentences]]
    return " ".join(summary_sentences)

def segment_and_extract_keywords_and_summarize(session_file, sentences_per_segment=6, top_k=8, print_preview=True):
    # Read transcript
    with open(session_file, "r", encoding="utf-8") as f:
        text = f.read()

    # Preprocess text
    clean_text = preprocess_for_topics(text)

    # Add paragraph breaks (TextTiling style)
    paragraph_text = add_paragraph_breaks(clean_text, sentences_per_paragraph=sentences_per_segment)
    segments = paragraph_text.split("\n\n")

    session_results = []
    for i, seg in enumerate(segments, 1):
        keywords = extract_keywords_tfidf(seg, top_k=top_k)
        summary = summarize_segment(seg, keywords)
        session_results.append({
            "segment_number": i,
            "text": seg,
            "keywords": keywords,
            "summary": summary
        })
        if print_preview:
            print(f"\n--- Segment {i} ---")
            print(f"Text: {seg[:300]}...")
            print(f"Keywords: {keywords}")
            print(f"Summary: {summary}\n")

    return session_results

