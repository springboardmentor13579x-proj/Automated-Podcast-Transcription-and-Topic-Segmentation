# ----------------- Keyword / phrase search across segments -----------------

def search_keyword_summary(all_sessions_results, keyword, speaker=None):
    """
    Search all sessions for a keyword and return the summaries of relevant segments.

    Parameters:
    - all_sessions_results: dict of session -> segments info
    - keyword: str, word/phrase to search
    - speaker: str or None, if you want to filter by speaker (requires transcripts with speaker tags)

    Returns:
    - dict of session -> list of matched segments with summaries
    """
    keyword = keyword.lower()
    results = {}

    for session, segments in all_sessions_results.items():
        matched_segments = []
        for seg in segments:
            seg_text = seg['text'].lower()
            if keyword in seg_text:
                # Optional speaker filter
                if speaker:
                    if speaker.lower() not in seg_text:
                        continue
                matched_segments.append({
                    "segment_number": seg["segment_number"],
                    "keywords": seg["keywords"],
                    "summary": seg["summary"],
                    "text": seg["text"]
                })
        if matched_segments:
            results[session] = matched_segments

    return results

