from difflib import SequenceMatcher

def highlight_differences(ref, hyp):
    ref_words = ref.split()
    hyp_words = hyp.split()

    sm = SequenceMatcher(None, ref_words, hyp_words)
    diff_output = []

    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            diff_output.extend(ref_words[i1:i2])
        elif tag == "replace":
            diff_output.extend([f"[{w}]" for w in hyp_words[j1:j2]])
        elif tag == "insert":
            diff_output.extend([f"[+{w}]" for w in hyp_words[j1:j2]])
        elif tag == "delete":
            diff_output.extend([f"[-{w}]" for w in ref_words[i1:i2]])

    return " ".join(diff_output)

