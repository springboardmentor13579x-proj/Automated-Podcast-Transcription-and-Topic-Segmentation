# Helper to clean session name from filename
def clean_session_name(filename):
    # Remove suffix like ".A.words.xml" and extra (1),(2)
    session = re.sub(r'\s*\(\d+\)', '', filename)  # remove (1),(2)
    session = session.split('.')[0]  # ES2002a
    return session

# Group transcripts by cleaned session
sessions = {}
for f in os.listdir(TRANSCRIPT_PATH):
    if f.endswith(".words.xml"):
        session = clean_session_name(f)
        sessions.setdefault(session, []).append(f)

# Parse XML and combine text per session
for session, files in sessions.items():
    combined_text = ""
    # Sort files by part (A, B, C, D)
    files_sorted = sorted(files, key=lambda x: re.search(r'\.([A-D])\.words\.xml', x).group(1))

    for file in files_sorted:
        tree = ET.parse(os.path.join(TRANSCRIPT_PATH, file))
        root = tree.getroot()
        for w in root.iter('w'):
            combined_text += (w.text or "") + " "

    combined_text = combined_text.strip()

    # Save combined transcript
    output_file = os.path.join(OUTPUT_PATH, f"{session}.txt")
    with open(output_file, 'w', encoding='utf-8') as f_out:
        f_out.write(combined_text)

    print(f"Processed {session} -> {output_file}")

