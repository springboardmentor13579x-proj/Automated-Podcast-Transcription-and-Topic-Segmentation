# ----------------- Existing preprocessing & keyword extraction -----------------

def preprocess_for_topics(text):
    import re
    text = text.lower()
    text = re.sub(r"\b(uh|um|erm|ah|mm|hmm)\b", "", text)
    text = re.sub(r"[^a-z0-9\.\s]", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()

def add_paragraph_breaks(text, sentences_per_paragraph=6):
    sentences = sent_tokenize(text)
    paragraphs = []
    for i in range(0, len(sentences), sentences_per_paragraph):
        para = " ".join(sentences[i:i+sentences_per_paragraph])
        paragraphs.append(para)
    return "\n\n".join(paragraphs)

def extract_keywords_tfidf(text, top_k=8):
    vectorizer = TfidfVectorizer(
        stop_words="english",
        max_df=1.0,
        min_df=1
    )
    tfidf = vectorizer.fit_transform([text])
    scores = tfidf.toarray()[0]
    terms = vectorizer.get_feature_names_out()
    ranked = sorted(zip(terms, scores), key=lambda x: x[1], reverse=True)
    keywords = [term for term, score in ranked[:top_k]]
    return keywords

